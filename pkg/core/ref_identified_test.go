//ff:what TestRefIdentified — a 5Q code folds to its scheme's Identified code in either section; other codes stay
package core

import "testing"

func TestRefIdentified(t *testing.T) {
	for c, want := range map[uint16]uint16{
		0x05: 0x05, 0x09: 0x05, 0x1D: 0x19, 0x20: 0x20, 0x24: 0x20, 0x26: 0x25, 0x3D: 0x39,
		0x00: 0x00, 0x04: 0x04, 0x1E: 0x1E, 0x1F: 0x1F, 0x3E: 0x3E, 0x40: 0x40, 0x42: 0x42, 0x5F: 0x5F,
	} {
		if got := RefIdentified(c); got != want {
			t.Fatalf("C %X: %X, want %X", c, got, want)
		}
	}
}
