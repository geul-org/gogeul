//ff:func feature=schema type=rule control=iteration dimension=1
//ff:what TestEdgeDefined — assigned direct Edge codes and EDGE-ISSUER 0x13D~0x13F are defined; Reserved 0x7C~0x7F, the empty 0x80~0x13C and gaps are not
package schema

import "testing"

func TestEdgeDefined(t *testing.T) {
	for _, c := range []uint16{0x00, 0x03, 0x06, 0x0B, 0x12, 0x1A, 0x1D, 0x20, 0x59, 0x65, 0x6A, 0x76, 0x79, 0x80, 0x89, 0x94, 0x13D, 0x13E, 0x13F} {
		if !edgeDefined(c) {
			t.Fatalf("0x%03X: want defined", c)
		}
	}
	for _, c := range []uint16{0x07, 0x0C, 0x40, 0x1F, 0x21, 0x26, 0x27, 0x5A, 0x66, 0x77, 0x7A, 0x7C, 0x7D, 0x7F, 0x95, 0xBD, 0x100, 0x13C, 0x140} {
		if edgeDefined(c) {
			t.Fatalf("0x%03X: want reserved", c)
		}
	}
}
